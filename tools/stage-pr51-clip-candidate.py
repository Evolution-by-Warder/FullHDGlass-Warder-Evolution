#!/usr/bin/env python3
"""Stage TEST54 default ChannelSelection overlay in a temporary payload only.

Never run against the approved checked-in skin.xml. In production the same
overlay is generated by cChannelsel() into the active runtime skin.
"""
import re
from pathlib import Path


def stage_skin(skin_path):
    skin_path = Path(skin_path)
    content = skin_path.read_text(encoding="utf-8")
    pattern = re.compile(r'<screen\b[^>]*name="ChannelSelection"[^>]*>.*?</screen>', re.S)
    matches = list(pattern.finditer(content))
    if len(matches) != 1:
        raise RuntimeError("Expected exactly one default ChannelSelection screen")
    match = matches[0]
    screen = match.group(0)
    if 'render="WarderChannelEpgClip"' in screen:
        raise RuntimeError("Default ChannelSelection already contains event overlay")
    # Preserve font sizes and all other screens; only relocate default EPG
    # description and draw fitted titles on top of original progress bars.
    old = 'render="g17MetrixHDRunningText"'
    if screen.count(old) != 1:
        raise RuntimeError("Missing original description renderer")
    screen = screen.replace(old, old + ' warderWholeLineScroll="1"', 1)
    old_size = 'size="685,240"'
    if screen.count(old_size) != 1:
        raise RuntimeError("Unexpected description geometry")
    screen = screen.replace(old_size, 'size="685,224"', 1)
    old_epg = 'position="1150,685" size="685,236"'
    if screen.count(old_epg) != 1:
        raise RuntimeError("Unexpected upcoming EPG geometry")
    screen = screen.replace(old_epg, 'position="1150,695" size="685,226"', 1)
    if screen.count('numEvents="8"') != 1:
        raise RuntimeError("Unexpected default upcoming EPG count")
    screen = screen.replace('numEvents="8"', 'numEvents="6"', 1)
    list_pattern = re.compile(r'<widget\s+name="list"[^>]*picServiceEventProgressbar=[^>]*\s/>')
    m = list_pattern.search(screen)
    if m is None:
        raise RuntimeError("No native progressbar row list in default screen")
    if 'fieldMargins=' not in m.group():
        patched = m.group().replace('/>', ' fieldMargins="26" />')
        screen = screen[:m.start()] + patched + screen[m.end():]
    overlay = ('    <widget source="ServiceEvent" render="WarderChannelEpgClip" '
               'position="60,96" size="1065,842" zPosition="4" transparent="1" />')
    screen = screen.replace('</screen>', overlay + '\n  </screen>', 1)
    content = content[:match.start()] + screen + content[match.end():]
    skin_path.write_text(content, encoding="utf-8")
    return content


if __name__ == "__main__":
    import sys
    if len(sys.argv) != 2:
        raise SystemExit("usage: stage-pr51-clip-candidate.py /tmp/PAYLOAD/usr/share/.../skin.xml")
    stage_skin(sys.argv[1])
